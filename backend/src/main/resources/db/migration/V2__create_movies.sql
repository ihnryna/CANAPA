CREATE TABLE movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id BIGINT,
    imdb_id VARCHAR(20),
    title VARCHAR(300) NOT NULL,
    description TEXT,
    rating DOUBLE PRECISION,
    runtime INTEGER,
    release_year INTEGER,
    poster_url VARCHAR(1000),
    original_language VARCHAR(10),
    director VARCHAR(300),
    actors TEXT,
    writers TEXT,
    rated VARCHAR(30),
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_movies_title_not_blank CHECK (char_length(btrim(title)) > 0),
    CONSTRAINT ck_movies_rating CHECK (rating IS NULL OR rating BETWEEN 0 AND 10),
    CONSTRAINT ck_movies_runtime CHECK (runtime IS NULL OR runtime > 0),
    CONSTRAINT ck_movies_release_year CHECK (release_year IS NULL OR release_year > 0)
);
CREATE UNIQUE INDEX idx_movies_tmdb_id ON movies (tmdb_id);
CREATE INDEX idx_movies_imdb_id ON movies (imdb_id);
CREATE INDEX idx_movies_title ON movies (title);

CREATE TABLE movie_genres (
    movie_id BIGINT NOT NULL,
    genre VARCHAR(100) NOT NULL,
    CONSTRAINT pk_movie_genres PRIMARY KEY (movie_id, genre),
    CONSTRAINT ck_movie_genres_genre_not_blank CHECK (char_length(btrim(genre)) > 0),
    CONSTRAINT fk_movie_genres_movie FOREIGN KEY (movie_id) REFERENCES movies (id) ON DELETE CASCADE
);
