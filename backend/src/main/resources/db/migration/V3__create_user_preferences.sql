CREATE TABLE user_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    room_id UUID NOT NULL,
    min_rating DOUBLE PRECISION,
    max_runtime INTEGER,
    preferred_language VARCHAR(10),
    text_preference TEXT,
    CONSTRAINT uk_user_room_preference UNIQUE (user_id, room_id),
    CONSTRAINT ck_user_preferences_min_rating CHECK (min_rating IS NULL OR min_rating BETWEEN 0 AND 10),
    CONSTRAINT ck_user_preferences_max_runtime CHECK (max_runtime IS NULL OR max_runtime BETWEEN 1 AND 600),
    CONSTRAINT fk_user_preferences_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_preferences_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE
);
CREATE INDEX idx_preferences_room ON user_preferences (room_id);
CREATE INDEX idx_preferences_user ON user_preferences (user_id);

CREATE TABLE preference_liked_genres (
    preference_id BIGINT NOT NULL,
    genre VARCHAR(100) NOT NULL,
    CONSTRAINT pk_preference_liked_genres PRIMARY KEY (preference_id, genre),
    CONSTRAINT ck_preference_liked_genre_not_blank CHECK (char_length(btrim(genre)) > 0),
    CONSTRAINT fk_preference_liked_genres_preference FOREIGN KEY (preference_id)
        REFERENCES user_preferences (id) ON DELETE CASCADE
);

CREATE TABLE preference_disliked_genres (
    preference_id BIGINT NOT NULL,
    genre VARCHAR(100) NOT NULL,
    CONSTRAINT pk_preference_disliked_genres PRIMARY KEY (preference_id, genre),
    CONSTRAINT ck_preference_disliked_genre_not_blank CHECK (char_length(btrim(genre)) > 0),
    CONSTRAINT fk_preference_disliked_genres_preference FOREIGN KEY (preference_id)
        REFERENCES user_preferences (id) ON DELETE CASCADE
);
