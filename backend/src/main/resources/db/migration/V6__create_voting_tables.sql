CREATE TABLE votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    room_id UUID NOT NULL,
    movie_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_vote_user_room_movie UNIQUE (user_id, room_id, movie_id),
    CONSTRAINT fk_votes_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_votes_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
    CONSTRAINT fk_votes_movie FOREIGN KEY (movie_id) REFERENCES movies (id) ON DELETE CASCADE
);

CREATE INDEX ix_votes_room_movie ON votes (room_id, movie_id);
CREATE INDEX ix_votes_user_id ON votes (user_id);

CREATE TABLE excluded_movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id UUID NOT NULL,
    movie_id BIGINT NOT NULL,
    excluded_by_user_id UUID NOT NULL,
    excluded_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_excluded_movie_room_movie UNIQUE (room_id, movie_id),
    CONSTRAINT fk_excluded_movies_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
    CONSTRAINT fk_excluded_movies_movie FOREIGN KEY (movie_id) REFERENCES movies (id) ON DELETE CASCADE,
    CONSTRAINT fk_excluded_movies_user FOREIGN KEY (excluded_by_user_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX ix_excluded_movies_user_id ON excluded_movies (excluded_by_user_id);

CREATE TABLE voting_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id UUID NOT NULL,
    vote_count INTEGER NOT NULL,
    finished_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_voting_result_room UNIQUE (room_id),
    CONSTRAINT ck_voting_results_vote_count CHECK (vote_count >= 0),
    CONSTRAINT fk_voting_results_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE
);

CREATE TABLE voting_result_winners (
    voting_result_id BIGINT NOT NULL,
    movie_id BIGINT NOT NULL,
    CONSTRAINT uk_voting_result_winner UNIQUE (voting_result_id, movie_id),
    CONSTRAINT fk_voting_result_winners_result FOREIGN KEY (voting_result_id)
        REFERENCES voting_results (id) ON DELETE CASCADE,
    CONSTRAINT fk_voting_result_winners_movie FOREIGN KEY (movie_id)
        REFERENCES movies (id) ON DELETE RESTRICT
);

CREATE INDEX ix_voting_result_winners_movie_id ON voting_result_winners (movie_id);
